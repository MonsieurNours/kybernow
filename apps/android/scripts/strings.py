def esc(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s

def write(path, idx, f):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Généré par apps/android/scripts/strings.py : modifier ce script, pas ce fichier. -->", "<resources>"]
    for row in S:
        key, text = row[0], row[idx]
        text = f(text)
        extra = ""
        fmt = ' formatted="true"' if "%" in text else ""
        out.append(f'    <string name="{key}"{extra}{fmt}>{esc(text)}</string>')
    out.append("</resources>")
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(out) + "\n", encoding="utf-8")

res = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "app/src/main/res"
keys = [r[0] for r in S]
assert len(keys) == len(set(keys)), "clé en double"
write(res / "values/strings.xml", 2, lambda s: s)
write(res / "values-fr/strings.xml", 1, fr)
print(len(S), "textes")
