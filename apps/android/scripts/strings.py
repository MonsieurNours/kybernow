"""Textes de l'app Android : (clé, français, anglais). Écrit values/ (anglais,
la langue de repli de toute langue autre que le français) et values-fr/, avec
la typographie française (espace fine insécable avant : ; ! ?, guillemets « »,
espace insécable avant %), et dans les deux langues une espace insécable entre
un nombre et son unité (120 Hz, 8,9 ms, 80 Mbit/s) et autour de ×.

Les textes communs à toutes les apps KyberNow Link sont ceux de
docs/link-ui.md, recopiés à l'identique.

    python3 apps/android/scripts/strings.py
"""
import re
import sys
from pathlib import Path

N = "\u202f"  # espace fine insécable
NB = "\u00a0"  # espace insécable

def units(s):
    s = re.sub(r"(%\d+\$[.\d]*[dfs]|\d) (?=(?:Hz|ms|Mbit/s|min)\b)", lambda m: m.group(1) + NB, s)
    return s.replace(" × ", NB + "×" + NB)

def fr(s):
    for p in [":", ";", "!", "?"]:
        s = s.replace(" " + p, N + p)
    s = re.sub(r"(\d) %(?!\d)", lambda m: m.group(1) + NB + "%", s)
    return units(s.replace("« ", "«" + N).replace(" »", N + "»"))

