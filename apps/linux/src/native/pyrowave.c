// La sonde du lancement : la bibliothèque, un device Vulkan qui convienne, un
// décodeur 128 × 128, l'image de test décodée et relue (quelques points, à 4
// près). 1 : PyroWave est possible ; 0 : non, `err` dit pourquoi (journal).
// `gpu` : la carte du device.
int kn_pw_probe(char *gpu, int gpulen, char *err, int errlen) {
    char e[256] = {0};
    kn_pw *d = kn_pw_open(128, 128, 0, 0, e, sizeof e);
    pthread_mutex_lock(&g_lock);
    set(gpu, gpulen, g_gpu);
    pthread_mutex_unlock(&g_lock);
    if (!d) {
        set(err, errlen, e);
        return 0;
    }
    static uint8_t y[128 * 128], u[64 * 64], v[64 * 64];
    uint8_t *out[3] = {y, u, v};
    const int stride[3] = {128, 64, 64};
    int r = kn_pw_decode(d, sample, sizeof sample, out, stride, 1, 0);
    kn_pw_close(d);
    if (r != 1) {
        snprintf(e, sizeof e, "image de test non décodée (%d)", r);
        set(err, errlen, e);
        return 0;
    }
    static const int xs[] = {0, 32, 64, 96, 127};
    for (int i = 0; i < 5; i++) {
        double want = 16.0 + xs[i] * 219.0 / 127.0;
        if (abs((int)y[64 * 128 + xs[i]] - (int)(want + 0.5)) > 4) {
            snprintf(e, sizeof e, "image de test fausse (Y %d au lieu de %.0f en x = %d)", y[64 * 128 + xs[i]], want, xs[i]);
            set(err, errlen, e);
            return 0;
        }
    }
    static const int cs[] = {0, 31, 63};
    for (int i = 0; i < 3; i++) {
        if (abs((int)u[32 * 64 + cs[i]] - 128) > 4 || abs((int)v[32 * 64 + cs[i]] - 128) > 4) {
            set(err, errlen, "image de test fausse (chroma)");
            return 0;
        }
    }
    return 1;
}
