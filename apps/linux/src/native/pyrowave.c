// Décodage PyroWave (docs/pyrowave-client-linux.md) : codec par ondelettes,
// intra seul, décodé sur la carte graphique par Vulkan (API C de l'amont,
// libpyrowave-shared.so.1, compilée par scripts/build.sh au commit de la
// Station). La bibliothèque est chargée au lancement (dlopen) : sans elle, ou
// sans Vulkan 1.3 qui convienne, PyroWave est indisponible et rien d'autre ne
// change (le Raspberry Pi ne la cherche même pas).
//
// Voie simple, mesurée d'abord : PyroWave décode sur la carte puis relit les
// plans dans la mémoire du processeur (chemin « CPU buffer » de l'amont), en
// I420 (SDR 4:2:0), I010 (HDR10 4:2:0, 10 bits en bits de poids faible) ou en
// trois plans 4:4:4 convertis en BGRA (decoder.c) ; l'image suit ensuite le
// chemin de FFmpeg (copie vers SDL, sous-surface HDR).
//
// Un seul device PyroWave pour tout le processus (création coûteuse :
// pipelines) ; ses appels sont pris sous un verrou (plusieurs écrans : un
// décodeur par fil d'image, une file Vulkan).

